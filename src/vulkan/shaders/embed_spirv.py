"""Regenerates ahb_copy_spirv.hpp from the GLSL sources next to it.

usage: python embed_spirv.py <path to glslc>
(glslc ships with the Android NDK: <ndk>/shader-tools/<host>/glslc)
"""
import os
import subprocess
import sys
import tempfile

here = os.path.dirname(os.path.abspath(__file__))
glslc = sys.argv[1]
out = ["// Generated by embed_spirv.py from ahb_copy.vert / ahb_copy.frag: do not edit.",
       "#pragma once", "", "#include <cstdint>", "",
       "namespace systems::leal::campello_gpu::shaders {", ""]
for stage, name in (("vert", "kAhbCopyVert"), ("frag", "kAhbCopyFrag")):
    with tempfile.TemporaryDirectory() as tmp:
        spv = os.path.join(tmp, "out.spv")
        subprocess.run([glslc, "--target-env=vulkan1.1", "-O", os.path.join(here, f"ahb_copy.{stage}"), "-o", spv],
                       check=True)
        data = open(spv, "rb").read()
    words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
    out.append(f"    inline constexpr uint32_t {name}[] = {{")
    for i in range(0, len(words), 8):
        out.append("        " + ", ".join(f"0x{w:08x}u" for w in words[i:i + 8]) + ",")
    out.append("    };")
    out.append("")
out.append("}")
open(os.path.join(here, "ahb_copy_spirv.hpp"), "w", newline="\n").write("\n".join(out) + "\n")
print("ok")
